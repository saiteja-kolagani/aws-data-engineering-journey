SELECT UPPER(FIRST_NAME) AS UPPPER_FN, 
LOWER(LAST_NAME) AS LOWER_LN,
INITCAP(CONCAT(FIRST_NAME, LAST_NAME)) AS FULL_NAME,
CONCAT_WS('@', FIRST_NAME, LAST_NAME) AS FULL_N,
LEFT(FIRST_NAME, 3) AS F_3,
RIGHT(LAST_NAME, 3) AS R_3,
SPLIT_PART(CONCAT_WS('@', FIRST_NAME, LAST_NAME),'@', 1) AS SPLIT,
SUBSTRING(FIRST_NAME FROM 1 FOR 4),
LENGTH(FIRST_NAME) AS LEN,
TRIM(LAST_NAME) AS TRIM_L,
BTRIM(LAST_NAME, 's'),
LTRIM(LAST_NAME),
RTRIM(FIRST_NAME),
POSITION('e' IN FIRST_NAME),
REPLACE(LAST_NAME, 'e', '#' ),
LPAD(FIRST_NAME, 10, '&'),
*
FROM ACTOR;